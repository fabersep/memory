import * as crypto from 'node:crypto';
import * as fs from 'node:fs';
import * as path from 'node:path';
import { getCompiledL0Path, getHomeDir, getStateDir, withStateLock } from './config.js';
import { formatHygieneErrors, scanHygiene } from './hygiene.js';
import { appendMetric, CompileTrigger } from './metrics.js';
import {
  loadScopeFromHead,
  PROJECT_MEMORY_REL_DIR,
  resolveProjectRoot,
} from './store.js';
import {
  COMPILER_VERSION,
  MemoryEntry,
  Scope,
  UserConfig,
} from './types.js';

export function estimateTokens(text: string): number {
  return Math.ceil(Buffer.byteLength(text, 'utf8') / 4);
}

export interface CompileResult {
  ok: boolean;
  output?: string;
  estimatedTokens: number;
  budget: number;
  outputPath?: string;
  errors: string[];
  warnings: string[];
}

export function renderEntryFullBody(entry: MemoryEntry): string {
  return `### ${entry.id} (${entry.type})\n\n${entry.body}`;
}

export function estimateCorpusTokens(entries: MemoryEntry[]): number {
  const active = entries
    .filter((e) => e.status === 'active')
    .sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0));
  if (active.length === 0) return 0;
  return estimateTokens(active.map(renderEntryFullBody).join('\n'));
}

function renderEntryL0(entry: MemoryEntry): string {
  if (entry.l0 === 'body') {
    return renderEntryFullBody(entry);
  }
  return `- \`${entry.id}\` (${entry.type}): ${entry.summary}`;
}

export function renderGlobalL0(teamEntries: MemoryEntry[], personalEntries: MemoryEntry[]): string {
  const teamActive = teamEntries
    .filter((e) => e.status === 'active' && (e.l0 === 'line' || e.l0 === 'body'))
    .sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0));

  const personalActive = personalEntries
    .filter((e) => e.status === 'active' && (e.l0 === 'line' || e.l0 === 'body'))
    .sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0));

  const sections: string[] = [
    `<!-- generated by @fabersep/memory v${COMPILER_VERSION} — do not edit manually -->`,
    '# Memory (L0)',
  ];

  if (teamActive.length > 0) {
    sections.push('## Team\n\n' + teamActive.map(renderEntryL0).join('\n'));
  }

  if (personalActive.length > 0) {
    sections.push('## Personal\n\n' + personalActive.map(renderEntryL0).join('\n'));
  }

  if (teamActive.length === 0 && personalActive.length === 0) {
    sections.push('_No active L0 memory entries._');
  }

  return sections.join('\n\n') + '\n';
}

export function compileGlobalL0(
  config: UserConfig,
  options: {
    homeDir?: string;
    checkOnly?: boolean;
    includeProjectCheck?: boolean;
    cwd?: string;
    standaloneRepoDir?: string;
    trigger?: CompileTrigger;
  } = {},
): CompileResult {
  const homeDir = options.homeDir || getHomeDir();
  const errors: string[] = [];
  const warnings: string[] = [];

  const teamScope = config.roots.team
    ? loadScopeFromHead(config.roots.team.path, 'team')
    : undefined;
  const personalScope = config.roots.personal
    ? loadScopeFromHead(config.roots.personal.path, 'personal')
    : undefined;

  // Standalone repo CI mode: if neither team nor personal is configured, or standaloneRepoDir is given
  const standaloneScope =
    options.standaloneRepoDir
      ? loadScopeFromHead(options.standaloneRepoDir, 'team')
      : !teamScope && !personalScope && options.checkOnly && options.cwd
        ? loadScopeFromHead(options.cwd, 'team')
        : undefined;

  const effectiveTeam = teamScope || standaloneScope;

  for (const sc of [effectiveTeam, personalScope]) {
    if (!sc) continue;
    for (const err of sc.errors) {
      errors.push(`[${err.scope}] ${err.filePath}: ${err.message}`);
    }
    if (sc.uncommittedFiles.length > 0) {
      warnings.push(
        `Uncommitted edits in ${sc.scope} root (${sc.uncommittedFiles.join(', ')}); compiled from committed HEAD only.`,
      );
    }
    for (const entry of sc.entries) {
      const contentToScan = `${entry.summary}\n${entry.body}`;
      const hygiene = scanHygiene(contentToScan);
      if (hygiene.length > 0) {
        errors.push(formatHygieneErrors(hygiene, `[${entry.scope}] ${entry.filePath}`));
      }
    }
  }

  // Check duplicate active IDs across team and personal
  const teamActiveMap = new Map<string, MemoryEntry>();
  for (const e of effectiveTeam?.entries || []) {
    if (e.status !== 'active') continue;
    if (teamActiveMap.has(e.id)) {
      errors.push(`Duplicate active entry ID "${e.id}" within team scope.`);
    }
    teamActiveMap.set(e.id, e);
  }

  const personalActiveMap = new Map<string, MemoryEntry>();
  for (const e of personalScope?.entries || []) {
    if (e.status !== 'active') continue;
    if (personalActiveMap.has(e.id)) {
      errors.push(`Duplicate active entry ID "${e.id}" within personal scope.`);
    }
    if (teamActiveMap.has(e.id)) {
      errors.push(
        `Duplicate active entry ID "${e.id}" across scopes "team" and "personal". Resolve the collision before compiling.`,
      );
    }
    personalActiveMap.set(e.id, e);
  }

  // Optional project-level check (only in compile --check when inside a project repo)
  if (options.includeProjectCheck) {
    const projRes = resolveProjectRoot(undefined, options.cwd || process.cwd());
    if (projRes.source !== 'none' && projRes.projectRoot) {
      const projScope = loadScopeFromHead(
        projRes.projectRoot,
        'project',
        PROJECT_MEMORY_REL_DIR,
      );
      for (const err of projScope.errors) {
        errors.push(`[project] ${err.filePath}: ${err.message}`);
      }
      for (const entry of projScope.entries) {
        const hygiene = scanHygiene(`${entry.summary}\n${entry.body}`);
        if (hygiene.length > 0) {
          errors.push(formatHygieneErrors(hygiene, `[project] ${entry.filePath}`));
        }
        if (entry.status === 'active') {
          if (teamActiveMap.has(entry.id)) {
            errors.push(
              `Duplicate active entry ID "${entry.id}" across scopes "project" and "team".`,
            );
          }
          if (personalActiveMap.has(entry.id)) {
            errors.push(
              `Duplicate active entry ID "${entry.id}" across scopes "project" and "personal".`,
            );
          }
        }
      }
    }
  }

  const output = renderGlobalL0(effectiveTeam?.entries || [], personalScope?.entries || []);
  const outHygiene = scanHygiene(output);
  if (outHygiene.length > 0) {
    errors.push(formatHygieneErrors(outHygiene, 'compiled MEMORY.md'));
  }

  const tokens = estimateTokens(output);
  if (tokens > config.tokenBudget) {
    const contributors = [
      ...(effectiveTeam?.entries || []),
      ...(personalScope?.entries || []),
    ]
      .filter((e) => e.status === 'active' && (e.l0 === 'line' || e.l0 === 'body'))
      .map((e) => ({
        id: e.id,
        scope: e.scope,
        tokens: estimateTokens(renderEntryL0(e)),
      }))
      .sort((a, b) => b.tokens - a.tokens)
      .slice(0, 10);

    const list = contributors
      .map((c) => `  - ${c.id} (${c.scope}): ~${c.tokens} tokens`)
      .join('\n');
    errors.push(
      `Compiled L0 exceeds token budget (${tokens} > ${config.tokenBudget} estimated tokens). Largest entries:\n${list}`,
    );
  }

  if (errors.length > 0) {
    return {
      ok: false,
      estimatedTokens: tokens,
      budget: config.tokenBudget,
      errors,
      warnings,
    };
  }

  const outputPath = getCompiledL0Path(homeDir);
  if (!options.checkOnly) {
    let initial = false;
    let changed = false;
    const newHash = crypto.createHash('sha256').update(output, 'utf8').digest('hex');

    withStateLock(() => {
      const stateDir = getStateDir(homeDir);
      fs.mkdirSync(stateDir, { recursive: true });
      if (fs.existsSync(outputPath)) {
        const priorBytes = fs.readFileSync(outputPath);
        const priorHash = crypto.createHash('sha256').update(priorBytes).digest('hex');
        initial = false;
        changed = priorHash !== newHash;
      } else {
        initial = true;
        changed = false;
      }
      const tmpPath = path.join(
        stateDir,
        `MEMORY.md.tmp.${process.pid}.${crypto.randomBytes(4).toString('hex')}`,
      );
      fs.writeFileSync(tmpPath, output, 'utf8');
      fs.renameSync(tmpPath, outputPath);
    }, homeDir);

    const activeGlobalEntries = [
      ...(effectiveTeam?.entries || []),
      ...(personalScope?.entries || []),
    ].filter((e) => e.status === 'active');

    appendMetric(
      {
        type: 'compile',
        ts: new Date().toISOString(),
        trigger: options.trigger || 'cli',
        initial,
        changed,
        l0_sha256: newHash,
        l0_tokens: tokens,
        corpus_tokens: estimateCorpusTokens(activeGlobalEntries),
        active_entries: activeGlobalEntries.length,
      },
      homeDir,
    );
  }

  return {
    ok: true,
    output,
    estimatedTokens: tokens,
    budget: config.tokenBudget,
    outputPath,
    errors: [],
    warnings,
  };
}
